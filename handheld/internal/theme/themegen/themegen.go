// Package themegen writes the pak's colour table (theme_gen.go) from the
// committed snapshot of the Blackfyre design system's tokens.json (openspec
// change handheld-pak, design D8). The theme package's test regenerates it
// in memory and compares, so the table cannot drift from the snapshot.
//
// Refreshing the snapshot is a manual step: read the design system's
// project/tokens.json (https://claude.ai/artifact/JX4X2WDSVT48H94TboBR6V,
// with the Artifact tool's read action and path "project/tokens.json"),
// save it over handheld/internal/theme/tokens.json, then run
// `go generate ./internal/theme` in handheld/.
package themegen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"regexp"
	"strconv"
	"strings"
)

// Tokens is every token the screen draws with, in the order written. The
// dark app rules take each colour's "light" theme value, which is the dark
// panels' palette (bf-surface is the text on dark panels).
var Tokens = []string{
	"bf-ink",
	"bf-ink-raised",
	"bf-ink-code",
	"bf-ink-card-hover",
	"bf-ink-chip",
	"bf-ink-deep",
	"bf-surface",
	"bf-ink-subtle",
	"bf-accent",
	"bf-accent-on-dark",
	"bf-on-accent",
	"bf-ok",
	"bf-warn",
}

// OutlineToken is the panels' outline, a shadow token whose colour is
// taken from its inset outline.
const OutlineToken = "bf-shadow-outline-dark"

// Theme is the theme value read for every token.
const Theme = "light"

type tokenFile struct {
	Color struct {
		Tokens []token `json:"tokens"`
	} `json:"color"`
	Shadow struct {
		Tokens []token `json:"tokens"`
	} `json:"shadow"`
}

type token struct {
	Name  string            `json:"name"`
	Value map[string]string `json:"value"`
}

var hexColour = regexp.MustCompile(`#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b`)

// parseHex reads "#rrggbb" or "#rgb".
func parseHex(s string) (uint32, error) {
	m := hexColour.FindStringSubmatch(s)
	if m == nil {
		return 0, fmt.Errorf("no colour in %q", s)
	}
	h := m[1]
	if len(h) == 3 {
		h = string([]byte{h[0], h[0], h[1], h[1], h[2], h[2]})
	}
	v, err := strconv.ParseUint(h, 16, 32)
	return uint32(v), err
}

// GoName is a token's Go name: bf-ink-card-hover is InkCardHover.
func GoName(tok string) string {
	var b strings.Builder
	for _, p := range strings.Split(strings.TrimPrefix(tok, "bf-"), "-") {
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

// Generate writes theme_gen.go's source from the tokens.json contents.
func Generate(tokensJSON []byte) ([]byte, error) {
	var f tokenFile
	if err := json.Unmarshal(tokensJSON, &f); err != nil {
		return nil, fmt.Errorf("tokens.json: %w", err)
	}
	find := func(list []token, name string) (string, error) {
		for _, t := range list {
			if t.Name == name {
				v, ok := t.Value[Theme]
				if !ok {
					return "", fmt.Errorf("token %s has no %q value", name, Theme)
				}
				return v, nil
			}
		}
		return "", fmt.Errorf("token %s is missing from tokens.json", name)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by go generate (internal/theme/gen) from tokens.json; DO NOT EDIT.\n\n")
	b.WriteString("package theme\n\n")
	b.WriteString("// The Blackfyre tokens the screen draws with (the " + Theme + " theme values).\n")
	b.WriteString("var (\n")
	write := func(name, raw string) error {
		v, err := parseHex(raw)
		if err != nil {
			return fmt.Errorf("token %s: %w", name, err)
		}
		fmt.Fprintf(&b, "\t%s = Color{R: 0x%02x, G: 0x%02x, B: 0x%02x} // %s %s\n",
			GoName(name), v>>16&0xff, v>>8&0xff, v&0xff, name, strings.ToLower(hexColour.FindString(raw)))
		return nil
	}
	for _, name := range Tokens {
		raw, err := find(f.Color.Tokens, name)
		if err != nil {
			return nil, err
		}
		if err := write(name, raw); err != nil {
			return nil, err
		}
	}
	raw, err := find(f.Shadow.Tokens, OutlineToken)
	if err != nil {
		return nil, err
	}
	if !strings.Contains(raw, "inset 0 0 0") {
		return nil, fmt.Errorf("token %s: %q is not an inset outline", OutlineToken, raw)
	}
	if err := write(OutlineToken, raw); err != nil {
		return nil, err
	}
	b.WriteString(")\n")
	return format.Source(b.Bytes())
}
